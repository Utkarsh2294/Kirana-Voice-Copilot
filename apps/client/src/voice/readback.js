export function buildBillReadback({ lines, items, total, lang }) {
  const w = words[lang] || words['en-IN'],
    n = (value) => new Intl.NumberFormat(lang, { maximumFractionDigits: 3 }).format(value);
  if (!lines.length) return w[2];
  const byId = new Map(items.map((item) => [item.id, item]));
  return [
    w[0],
    ...lines.map((line) => {
      const item = byId.get(line.id),
        name = item?.names[lang.split('-')[0]] || item?.names.en || line.id;
      return `${name}. ${n(line.qtyBase / line.unitSize)} ${w[line.unit === 'L' ? 4 : line.unit === 'pc' ? 5 : 3]}. ${n(lineAmount(line.qtyBase, line.pricePaise, line.unitSize) / 100)} ${w[6]}`;
    }),
    `${w[1]}. ${n(total / 100)} ${w[6]}`,
  ].join('. ');
}
